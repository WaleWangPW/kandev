function isUiLocale(value: string | null): value is UiLocale {
  return value !== null && UI_LOCALES.includes(value as UiLocale);
}

function getTestLocale(): UiLocale | null {
  const value = (globalThis as Record<string, unknown>)[TEST_LOCALE_KEY];
  return typeof value === "string" && isUiLocale(value) ? value : null;
}

export function getUiLocale(): UiLocale {
  const testLocale = getTestLocale();
  if (testLocale) return testLocale;
  if (typeof window === "undefined") return DEFAULT_LOCALE;
  try {
    const stored = window.localStorage.getItem(STORAGE_KEY);
    return isUiLocale(stored) ? stored : DEFAULT_LOCALE;
  } catch {
    return DEFAULT_LOCALE;
  }
}

export function setUiLocale(locale: UiLocale): void {
  if (typeof window === "undefined") return;
  if (getUiLocale() === locale) return;
  try {
    window.localStorage.setItem(STORAGE_KEY, locale);
  } catch {
    // A private-mode or quota failure must not block the one-session switch.
  }
  window.dispatchEvent(new Event(LOCALE_CHANGE_EVENT));
  // Some existing display helpers are deliberately framework-agnostic and do
  // not subscribe to React state. A same-route reload ensures that every
  // stored state label is rendered in the selected locale without changing
  // task, workflow, or session data.
  window.location.reload();
}

function subscribe(onStoreChange: () => void): () => void {
  window.addEventListener(LOCALE_CHANGE_EVENT, onStoreChange);
  window.addEventListener("storage", onStoreChange);
  return () => {
    window.removeEventListener(LOCALE_CHANGE_EVENT, onStoreChange);
    window.removeEventListener("storage", onStoreChange);
  };
}

export function translate(value: string, locale = getUiLocale()): string {
  return locale === "zh-CN"
    ? (ZH_CN[value] ?? LEGACY_ZH_CN[value] ?? EXTENDED_ZH_CN[value] ?? value)
    : value;
}

const DOM_TRANSLATABLE_ATTRIBUTES = ["aria-label", "title", "placeholder", "data-placeholder"];
const DOM_SKIP_TAGS = new Set([
  "CODE",
  "PRE",
  "SCRIPT",
  "STYLE",
  "TEXTAREA",
  "INPUT",
]);

function canTranslateDomNode(node: Node): boolean {
  let element: Element | null = node.nodeType === Node.ELEMENT_NODE ? (node as Element) : node.parentElement;
  while (element) {
    if (DOM_SKIP_TAGS.has(element.tagName) || element.hasAttribute("contenteditable")) return false;
    element = element.parentElement;
  }
  return true;
}

function canTranslateDomAttribute(element: Element): boolean {
  let current: Element | null = element;
  while (current) {
    if (current.tagName === "CODE" || current.tagName === "PRE" || current.tagName === "SCRIPT" || current.tagName === "STYLE") return false;
    if (current.hasAttribute("contenteditable")) return false;
    current = current.parentElement;
  }
  return true;
}

/**
 * Translate already-rendered, app-owned chrome that predates the hook-based
 * i18n migration. It deliberately skips code, terminal/editor input and
 * contenteditable/user-authored regions so task content and repository data
 * are never rewritten as a side effect of selecting Chinese UI.
 */
export function translateRenderedDom(root: ParentNode, locale = getUiLocale()): void {
  if (locale !== "zh-CN") return;

  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  const textNodes: Text[] = [];
  let current: Node | null = walker.nextNode();
  while (current) {
    textNodes.push(current as Text);
    current = walker.nextNode();
  }

  for (const textNode of textNodes) {
    if (!canTranslateDomNode(textNode)) continue;
    const raw = textNode.nodeValue ?? "";
    const trimmed = raw.trim();
    if (!trimmed || trimmed.length > 240) continue;
    const translated = translate(trimmed, locale);
    if (translated !== trimmed) {
      textNode.nodeValue = raw.replace(trimmed, translated);
    }
  }

  if (!(root instanceof Element || root instanceof Document)) return;
  const elements = root.querySelectorAll("*");
  for (const element of elements) {
    if (!canTranslateDomAttribute(element)) continue;
    for (const attribute of DOM_TRANSLATABLE_ATTRIBUTES) {
      const value = element.getAttribute(attribute);
      if (!value || value.length > 240) continue;
      const translated = translate(value.trim(), locale);
      if (translated !== value.trim()) element.setAttribute(attribute, translated);
    }
  }
}

export function useI18n() {
  const locale = useSyncExternalStore(subscribe, getUiLocale, () => DEFAULT_LOCALE);
  const t = useCallback((value: string) => translate(value, locale), [locale]);
  const setLocale = useCallback((nextLocale: UiLocale) => setUiLocale(nextLocale), []);
  return { locale, t, setLocale };
}
